// ------------------------------------------------------------
// PART 1: WHAT IS JAVASCRIPT? (in the simplest way possible)
// ------------------------------------------------------------
//
// Imagine a house. The bricks and walls are the HTML (the
// structure), the paint and decoration is the CSS (the looks),
// and JAVASCRIPT is the electricity - it makes things HAPPEN.
// Lights turn on, doors open, the bell rings.
//
// JavaScript is a PROGRAMMING LANGUAGE that runs in the browser
// (and on servers with Node.js). It makes web pages ALIVE:
// buttons respond, popups appear, data loads without refreshing.


// ------------------------------------------------------------
// PART 2: HOW JAVASCRIPT RUNS YOUR CODE
// ------------------------------------------------------------
//
// The computer reads your code TOP TO BOTTOM, LINE BY LINE,
// like a cook following a recipe. One instruction at a time.
//
// UNCOMMENT BELOW AND RUN IT:

// console.log("Step 1: Boil the water");
// console.log("Step 2: Add the rice");
// console.log("Step 3: Serve the food");


// ------------------------------------------------------------
// PART 3: TALKING TO THE SCREEN (console.log)
// ------------------------------------------------------------
//
// console.log() is your loudspeaker. Whatever you put inside
// the brackets gets printed to the screen so you can SEE it.
//
// UNCOMMENT BELOW AND RUN IT:

// console.log("Hello, students!");
// console.log(2026);
// console.log("2 + 2 is", 2 + 2);


// ------------------------------------------------------------
// PART 4: ADDING NOTES TO YOUR CODE (comments)
// ------------------------------------------------------------
//
// Comments are notes for HUMANS. The computer skips them
// completely. They start with two forward slashes: //
//
// UNCOMMENT BELOW AND RUN IT:

// // This line is a comment - the computer ignores it.
// console.log("Only this line actually runs.");
// // Comments help other developers (and future YOU) understand the code.


// ------------------------------------------------------------
// PART 5: JAVASCRIPT IS CASE-SENSITIVE
// ------------------------------------------------------------
//
// JS treats capital and small letters as DIFFERENT things.
// "name" and "Name" are two different variables!
//
// UNCOMMENT BELOW AND RUN IT:

// let name = "Ada";
// let Name = "Grace";
//
// console.log(name);   // Ada
// console.log(Name);   // Grace - a totally different variable


// ------------------------------------------------------------
// PART 6: STATEMENTS END WITH SEMICOLONS
// ------------------------------------------------------------
//
// A statement is one full instruction. The semicolon (;) is
// like the full stop at the end of a sentence.
//
// UNCOMMENT BELOW AND RUN IT:

// console.log("First instruction");
// console.log("Second instruction");
// console.log("Third instruction");


